#!/usr/bin/env python3
"""Write lib/engines.lua from the Palette catalog.

The UGen takes an engine's index in the eurorack repository's generated
engine_table.h. The Lua list keeps its own order: engines already in
lib/engines.lua stay where they are and new ones go to the end, because a
saved "model" param is a position in that list.

Run after updating the eurorack submodule, then rebuild the UGen.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EURORACK = ROOT / "ugen" / "eurorack"
TABLE = EURORACK / "alt_firmwares/palette_seed3/generated/all/engine_table.h"
CATALOG = EURORACK / "alt_firmwares/plaits_lab_catalog/catalog.json"
OUT = ROOT / "lib" / "engines.lua"


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    table = re.findall(r'X\((\d+), "([^"]+)", "([^"]+)"', TABLE.read_text())
    ugen_index = {engine_id: int(i) for i, engine_id, _ in table}
    catalog = {e["id"]: e for e in json.loads(CATALOG.read_text())["engines"]}

    order = []
    if OUT.exists():
        order = re.findall(r'id = "([^"]+)"', OUT.read_text())
    gone = [engine_id for engine_id in order if engine_id not in ugen_index]
    if gone:
        sys.exit("engines no longer in the catalog (edit lib/engines.lua "
                 "by hand to keep saved params meaningful): " + ", ".join(gone))
    order += [engine_id for _, engine_id, _ in table if engine_id not in order]

    lines = [
        "-- GENERATED by ugen/gen_engines.py from the Plaits Palette catalog.",
        "-- Order is append-only: a saved model param is a position here.",
        "-- ugen: the engine's index in the PlaitsPalette UGen.",
        "-- controls: what harmonics, timbre, morph and macro do.",
        "return {",
    ]
    for engine_id in order:
        e = catalog[engine_id]
        controls = ", ".join(lua_string(c) for c in e["controls"])
        lines.append(
            "  { id = %s, name = %s, family = %s, ugen = %d,\n"
            "    controls = { %s } }," % (
                lua_string(engine_id), lua_string(e["name"]),
                lua_string(e["family"]), ugen_index[engine_id], controls))
    lines.append("}")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print("%s: %d engines" % (OUT.relative_to(ROOT), len(order)))


if __name__ == "__main__":
    main()
